export function translate(locale, idText) {
  const clean = idText.replace(/\s*—\s*/g, ", ");
  if (normalizeLocale(locale) === "id") return clean;
  const translated = english[clean] ?? english[idText];
  if (!translated && process.env.NODE_ENV !== "production") {
    console.warn(`Missing English translation: ${idText}`);
  }
  return translated || clean;
}

export const createTranslator = (locale) => (text) => translate(locale, text);
